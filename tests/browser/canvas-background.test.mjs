import assert from 'node:assert/strict'
import test from 'node:test'
import { createServer } from 'node:http'
import { serveWorkspaceAsset } from '../../scripts/flow/workspace-assets.mjs'
import { createHarness } from './harness.mjs'

test('the blank Canvas uses shared color controls and keeps its background out of app edits', async () => {
  const h = await createHarness({
    canvas: true, dock: true, pendingEdits: true,
    colorCatalog: { source: 'theme.css', names: ['--ocean'] },
    appStyles: ':root { --ocean: #173f7a; }',
  })
  try {
    const flow = h.page.locator('#flow-toggle')
    const viewport = h.page.locator('#viewport')
    const color = h.host.getByRole('textbox', { name: 'Canvas background color' })
    const panel = h.host.locator('#inspector-panel')
    const opacity = h.field('Canvas background opacity')
    const visibility = h.host.getByRole('button', { name: 'Show canvas background' })
    const backgroundImage = () => viewport.evaluate(element => getComputedStyle(element).backgroundImage)
    const displayedColor = () => viewport.evaluate(element => {
      const canvas = document.createElement('canvas').getContext('2d', { willReadFrequently: true })
      canvas.fillStyle = getComputedStyle(element).backgroundColor
      canvas.fillRect(0, 0, 1, 1)
      return [...canvas.getImageData(0, 0, 1, 1).data]
    })

    await h.open()
    assert.equal(await color.isVisible(), false)
    await flow.click()
    assert.equal(await color.isVisible(), false)
    await panel.focus()
    await h.page.keyboard.press('Escape')
    await color.waitFor()
    assert.deepEqual(await displayedColor(), [242, 241, 238, 255])
    assert.equal(await backgroundImage(), 'none')
    assert.equal(await visibility.getAttribute('aria-pressed'), 'true')
    assert.equal(await visibility.evaluate(button => getComputedStyle(button).backgroundColor), 'rgba(0, 0, 0, 0)')
    assert.equal(await h.host.getByText('Background', { exact: true }).count(), 0)

    await color.fill('B04461')
    await color.press('Enter')
    assert.deepEqual(await displayedColor(), [176, 68, 97, 255])
    await h.host.getByRole('button', { name: 'Open canvas color picker' }).click()
    await h.host.getByRole('tab', { name: 'Custom' }).waitFor()
    const plane = h.host.getByRole('button', { name: /Saturation and brightness/ })
    const box = await plane.boundingBox()
    const saved = () => h.page.evaluate(() => localStorage.getItem('localhost-inspector.canvas-background'))
    const beforeDrag = await saved()
    await h.page.mouse.move(box.x + box.width / 3, box.y + box.height / 3)
    await h.page.mouse.down()
    const firstPoint = await displayedColor()
    await h.page.mouse.move(box.x + box.width * .8, box.y + box.height * .8, { steps: 4 })
    const secondPoint = await displayedColor()
    assert.notDeepEqual(firstPoint, secondPoint)
    assert.equal(await saved(), beforeDrag)
    await h.page.mouse.up()
    assert.deepEqual(await displayedColor(), secondPoint)
    assert.notEqual(await saved(), beforeDrag)
    await h.page.mouse.down()
    await h.page.mouse.move(box.x + 5, box.y + 5)
    await h.page.keyboard.press('Escape')
    await h.page.mouse.up()
    assert.deepEqual(await displayedColor(), secondPoint)
    await h.host.getByRole('button', { name: 'Open canvas color picker' }).click()
    await h.host.getByRole('tab', { name: 'Libraries' }).click()
    const ocean = h.host.getByRole('option', { name: /ocean/i })
    await ocean.click()
    assert.equal(await ocean.getAttribute('aria-selected'), 'true')
    assert.equal(await h.host.getByText(/^Style ·/).count(), 0)
    assert.deepEqual(await displayedColor(), [23, 63, 122, 255])
    await h.host.getByRole('button', { name: 'Close Variables' }).click()
    await h.app.evaluate(() => document.documentElement.style.setProperty('--ocean', '#2464a0'))
    await color.evaluate(input => { if (input.value !== '2464A0') throw Error('Applied style did not refresh') })
    assert.deepEqual(await displayedColor(), [36, 100, 160, 255])
    await opacity.fill('50')
    await opacity.press('Enter')
    const translucent = await displayedColor()
    assert.ok(translucent[0] > 36 && translucent[0] < 242)
    await visibility.focus()
    await visibility.press('Space')
    assert.equal(await visibility.getAttribute('aria-pressed'), 'false')
    assert.equal(await visibility.evaluate(button => button === button.getRootNode().activeElement), true)
    assert.equal(await visibility.evaluate(button => getComputedStyle(button).backgroundColor), 'rgba(0, 0, 0, 0)')
    assert.equal(await opacity.isDisabled(), true)
    assert.match(await backgroundImage(), /conic-gradient/)
    const checkerSize = await viewport.evaluate(element => getComputedStyle(element).backgroundSize)
    await h.page.locator('#zoom-preset').selectOption('0.25')
    assert.equal(await viewport.evaluate(element => getComputedStyle(element).backgroundSize), checkerSize)
    await visibility.press('Space')
    assert.equal(await opacity.isEnabled(), true)
    assert.equal(await opacity.inputValue(), '50')
    assert.equal(await backgroundImage(), 'none')
    assert.deepEqual(await displayedColor(), translucent)

    await h.select()
    assert.equal(await color.isVisible(), false)
    assert.deepEqual(await h.journal(), [])
    await panel.focus()
    await h.page.keyboard.press('Escape')
    await visibility.click()
    assert.match(await backgroundImage(), /conic-gradient/)
    await flow.click()
    assert.deepEqual(await displayedColor(), [0, 0, 0, 0])
    assert.equal(await backgroundImage(), 'none')
    assert.equal(new URLSearchParams(new URL(h.page.url()).hash.slice(1)).get('view'), null)
    await h.page.reload()
    await flow.click()
    assert.match(await backgroundImage(), /conic-gradient/)
  } finally { await h.close() }
})

test('section and frame titles select independent fills that preview and survive reload', async t => {
  const server = createServer(async (req, res) => {
    if (await serveWorkspaceAsset(req.url, res)) return
    res.writeHead(200, { 'content-type': 'text/html' }).end('<body style="background:white"><script type="module" src="/__inspector-flow/preview-wheel.mjs"></script>Draft</body>')
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  t.after(() => new Promise(resolve => server.close(resolve)))
  const h = await createHarness({ canvas: true, dock: true, flowVariants: [
    { id: 'draft', label: 'Draft', section: 'Examples', anchor: 'first', route: '/', origin: 'http://127.0.0.1:' + server.address().port },
  ] })
  try {
    const page = h.page
    await h.open()
    await page.locator('#flow-toggle').click()
    const title = page.getByRole('button', { name: 'Examples', exact: true })
    const wrapper = page.locator('[data-variant="draft"]')
    await title.press('Enter')
    const sectionColor = h.host.getByRole('textbox', { name: 'Section background color' })
    await sectionColor.fill('397242')
    await sectionColor.press('Enter')
    const surface = page.locator('.variant-section-surface')
    const surfaceFill = await surface.evaluate(node => node.style.backgroundColor)
    assert.ok(surfaceFill)
    const radius = h.field('Section corner radius')
    await radius.fill('20')
    await radius.press('Enter')
    assert.equal(await surface.evaluate(node => node.style.borderRadius), '20px')
    assert.equal(await h.field('Section width').getAttribute('aria-readonly'), 'true')
    const frameTitle = wrapper.getByRole('button', { name: 'Select Draft frame' })
    await frameTitle.press('Enter')
    const width = h.field('Frame width')
    await width.fill('700')
    await width.press('Enter')
    assert.equal(await wrapper.evaluate(node => node.offsetWidth), 700)
    const frameColor = h.host.getByRole('textbox', { name: 'Frame background color' })
    await frameColor.fill('B83560')
    await frameColor.press('Enter')
    const iframe = wrapper.locator('iframe')
    const frameFill = await iframe.evaluate(node => node.style.backgroundColor)
    assert.ok(frameFill)
    assert.notEqual(frameFill, surfaceFill)
    const weight = h.field('Frame stroke weight')
    await weight.fill('4')
    await weight.press('Enter')
    const stroke = h.host.getByRole('textbox', { name: 'Frame stroke color' })
    await stroke.fill('880044')
    await stroke.press('Enter')
    assert.equal(await iframe.evaluate(node => getComputedStyle(node).borderTopColor), 'rgb(136, 0, 68)')
    const picker = h.host.getByRole('button', { name: 'Open frame color picker' })
    await picker.click()
    const plane = h.host.getByRole('button', { name: /Saturation and brightness/ })
    const box = await plane.boundingBox()
    await page.mouse.move(box.x + 10, box.y + 10)
    await page.mouse.down()
    assert.notEqual(await iframe.evaluate(node => node.style.backgroundColor), frameFill)
    await page.keyboard.press('Escape')
    await page.mouse.up()
    assert.equal(await iframe.evaluate(node => node.style.backgroundColor), frameFill)
    const body = wrapper.frameLocator('iframe').locator('body')
    await body.evaluate(node => { if (getComputedStyle(node).backgroundColor !== 'rgba(0, 0, 0, 0)') throw Error('Opaque app backdrop') })
    await page.goto(page.url().split('#')[0] + '#context=1&frame=first&page=%2F&view=canvas&variant=draft')
    await page.reload()
    await frameTitle.waitFor()
    assert.equal(await wrapper.evaluate(node => node.offsetWidth), 700)
    assert.equal(await iframe.evaluate(node => getComputedStyle(node).borderTopWidth), '4px')
    assert.equal(await iframe.evaluate(node => node.style.backgroundColor), frameFill)
    assert.equal(await surface.evaluate(node => node.style.backgroundColor), surfaceFill)

  } finally { await h.close() }
})

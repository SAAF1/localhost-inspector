test('padding defaults to compact for matching opposing sides and preserves an explicit toggle', async () => {
  const h = await createHarness()
  try {
    await h.app.locator('#target').evaluate(node => { node.style.padding = '24px 0' })
    await h.open(); await h.select()
    assert.equal(await h.field('Horizontal padding').inputValue(), '0')
    assert.equal(await h.field('Vertical padding').inputValue(), '24')
    assert.equal(await h.field('Left padding').count(), 0)
    await h.host.getByRole('button', { name: 'Expand individual padding' }).click()
    const collapse = h.host.getByRole('button', { name: 'Collapse individual padding' })
    assert.equal(await collapse.evaluate(node => node === node.getRootNode().activeElement), true)
    await h.enter('Gap', 12); await h.settled()
    assert.equal(await h.field('Top padding').inputValue(), '24')
    assert.deepEqual((await h.journal()).map(edit => edit.property), ['gap'])
  } finally { await h.close() }
})

test('flex alignment represents stretch and distribution without releasing the other axis', async () => {
  const h = await createHarness()
  try {
    const target = h.app.locator('body > #target')
    await target.evaluate(node => {
      Object.assign(node.style, { flexDirection: 'column', alignItems: 'normal', justifyContent: 'normal', height: '200px' })
      const header = document.createElement('div')
      header.id = 'contained-header'
      header.style.cssText = 'container-type:inline-size;padding-inline:24px'
      header.textContent = 'Recent Sales'
      const body = document.createElement('div')
      body.textContent = 'Content'
      node.replaceChildren(header, body)
    })
    const header = target.locator('#contained-header')
    const before = await header.boundingBox()
    await h.open(); await h.select()
    const alignment = h.host.getByRole('group', { name: 'Container alignment' })
    const advanced = h.host.getByRole('button', { name: 'Auto layout settings' })
    const top = alignment.getByRole('button', { name: 'Align top', exact: true })
    const center = alignment.getByRole('button', { name: 'Align center', exact: true })
    assert.deepEqual(await alignment.getByRole('button').evaluateAll(buttons =>
      buttons.map(button => button.getAttribute('aria-label'))), ['Align top', 'Align center', 'Align bottom'])
    assert.equal(await top.getAttribute('aria-pressed'), 'true')
    await top.click()
    assert.equal((await h.journal()).length, 0)
    await advanced.click()
    assert.equal(await h.host.getByRole('button', { name: 'CSS cross-axis alignment' }).innerText(), 'Stretch')
    assert.equal(await h.host.getByRole('button', { name: 'Auto spacing' }).isDisabled(), true)
    assert.equal(await h.host.getByRole('group', { name: 'Align text baseline' }).getByRole('button', { name: 'On' }).isDisabled(), true)
    await h.page.keyboard.press('Escape')
    await center.press('Enter'); await h.settled()
    assert.equal(await center.getAttribute('aria-pressed'), 'true')
    assert.equal(await center.evaluate(node => node === node.getRootNode().activeElement), true)
    assert.equal(await h.css('justify-content'), 'center')
    assert.equal(await h.css('align-items'), 'normal')
    const after = await header.boundingBox()
    assert.equal(after.width, before.width)
    assert.equal(after.height, before.height)
    assert.ok(after.y > before.y, 'The chosen main-axis position moves the content')
    assert.deepEqual((await h.journal()).map(edit => edit.property), ['justify-content'])

    await target.evaluate(node => { node.style.justifyContent = 'space-between'; node.style.alignItems = 'center' })
    await h.select()
    assert.deepEqual(await alignment.getByRole('button').evaluateAll(buttons =>
      buttons.map(button => button.getAttribute('aria-label'))), ['Align left', 'Align center', 'Align right'])
    await advanced.click()
    assert.equal(await h.host.getByRole('button', { name: 'Auto spacing' }).innerText(), 'Between')
    assert.equal(await h.host.getByRole('button', { name: 'CSS cross-axis alignment' }).innerText(), 'Center')
    await h.page.keyboard.press('Escape')
    await alignment.getByRole('button', { name: 'Align right', exact: true }).click(); await h.settled()
    assert.equal(await h.css('justify-content'), 'space-between')
    assert.equal(await h.css('align-items'), 'end')
    assert.deepEqual((await h.journal()).map(edit => edit.property), ['justify-content', 'align-items'])
  } finally { await h.close() }
})

test('Gap owns the fixed and Auto switch while settings choose Auto distribution', async () => {
  const h = await createHarness()
  try {
    await h.app.locator('body > #target').evaluate(node => {
      Object.assign(node.style, { flexDirection: 'column', alignItems: 'stretch', justifyContent: 'start' })
    })
    await h.open(); await h.select()
    const alignment = h.host.getByRole('group', { name: 'Container alignment' })
    const gap = h.field('Gap')
    const gapOptions = h.host.getByRole('button', { name: 'Gap options' })
    const settings = h.host.getByRole('button', { name: 'Auto layout settings', exact: true })
    assert.equal(await gap.inputValue(), '8')
    await gapOptions.click()
    assert.equal(await h.host.getByRole('menuitemradio', { name: '8' }).getAttribute('aria-checked'), 'true')
    await h.host.getByRole('menuitemradio', { name: 'Auto' }).click()
    await h.settled()
    assert.equal(await gap.getAttribute('aria-valuetext'), 'Auto')
    assert.equal(await h.css('gap'), '8px')
    assert.equal(await h.css('justify-content'), 'space-between')
    assert.equal(await h.css('align-items'), 'stretch')
    assert.match(await alignment.getAttribute('aria-description'), /stretch/)
    assert.equal(await alignment.locator('.li-matrix-stretch').isVisible(), true)
    const right = alignment.getByRole('button', { name: 'Align right', exact: true })
    await right.hover()
    assert.equal(await right.locator('.li-matrix-auto-mark').isVisible(), true)
    await settings.click()
    const spacing = h.host.getByRole('button', { name: 'Auto spacing' })
    assert.equal(await spacing.innerText(), 'Between')
    const dialog = h.host.getByRole('dialog', { name: 'Auto layout settings' })
    await spacing.press('ArrowDown')
    const menu = dialog.getByRole('menu', { name: 'Auto spacing' })
    const between = menu.getByRole('menuitemradio', { name: 'Between' })
    assert.equal(await between.getAttribute('aria-checked'), 'true')
    await between.press('Escape')
    assert.equal(await menu.count(), 0)
    assert.equal(await dialog.isVisible(), true)
    await spacing.press('Escape')
    assert.equal(await dialog.count(), 0)
    assert.equal(await settings.evaluate(node => node === node.getRootNode().activeElement), true)
    await settings.click()
    await spacing.press('ArrowDown')
    await between.press('ArrowDown')
    await menu.getByRole('menuitemradio', { name: 'Evenly' }).press('Enter')
    await h.settled()
    assert.equal(await h.css('justify-content'), 'space-evenly')
    assert.equal(await h.css('align-items'), 'stretch')
    assert.equal(await dialog.isVisible(), true)
    assert.equal(await spacing.innerText(), 'Evenly')
    assert.equal(await spacing.evaluate(node => node === node.getRootNode().activeElement), true)
    await right.click()
    await h.settled()
    assert.equal(await right.getAttribute('aria-pressed'), 'true')
    assert.equal(await h.css('justify-content'), 'space-evenly')
    assert.equal(await h.css('align-items'), 'end')
    await gapOptions.click()
    assert.equal(await h.host.getByRole('menuitemradio', { name: 'Auto' }).getAttribute('aria-checked'), 'true')
    await h.host.getByRole('menuitemradio', { name: '8' }).click()
    await h.settled()
    assert.equal(await gap.inputValue(), '8')
    assert.equal(await h.css('justify-content'), 'start')
    assert.deepEqual((await h.journal()).map(edit => edit.property), ['justify-content', 'justify-content', 'align-items', 'justify-content'])
  } finally { await h.close() }
})

test('inline horizontal alignment follows physical positions in RTL', async () => {
  const h = await createHarness()
  try {
    const target = h.app.locator('body > #target')
    await target.evaluate(node => {
      Object.assign(node.style, {
        direction: 'rtl', flexDirection: 'column', justifyContent: 'space-between', alignItems: 'start',
      })
    })
    const child = target.locator('span').first()
    const before = await child.boundingBox()
    await h.open(); await h.select()
    const alignment = h.host.getByRole('group', { name: 'Container alignment' })
    assert.equal(await alignment.getByRole('button', { name: 'Align right' }).getAttribute('aria-pressed'), 'true')
    await alignment.getByRole('button', { name: 'Align left' }).click(); await h.settled()
    assert.equal(await h.css('align-items'), 'end')
    assert.equal(await h.css('justify-content'), 'space-between')
    const after = await child.boundingBox()
    assert.ok(after.x < before.x, 'The child moves physically left in RTL')
    assert.equal(after.y, before.y)
  } finally { await h.close() }
})

test('Inspector shortcuts reuse Parent and Undo and leave editing and app controls alone', async () => {
  const h = await createHarness({ dock: true })
  try {
    await h.open()
    const parent = h.host.getByRole('button', { name: 'Select parent element' })
    const undo = h.host.getByRole('button', { name: 'Undo last preview' })
    const shortcut = await undo.getAttribute('aria-keyshortcuts')
    const undoKeys = shortcut === 'Meta+Z' ? 'Meta+z' : 'Control+z'
    await h.select('#target > span:first-child')
    assert.equal(await parent.getAttribute('aria-keyshortcuts'), 'Shift+Enter')
    await h.page.keyboard.press('Shift+Enter')
    const target = h.app.locator('body > #target')
    const selection = h.app.locator('#localhost-inspector-outlines #outline')
    assert.deepEqual(await selection.boundingBox(), await target.boundingBox())
    await h.enter('Corner radius', 18); await h.settled()
    const panel = h.host.getByRole('region', { name: 'Design inspector' })
    assert.equal(await panel.evaluate(el => el === el.getRootNode().activeElement), true)

    await h.field('Corner radius').focus()
    await h.page.keyboard.press(undoKeys)
    assert.equal(await h.css('border-radius'), '18px')
    // Native text Undo may change a draft. Return it to the saved value before leaving the field.
    await h.field('Corner radius').fill('18')
    await h.app.locator('#other').focus()
    await h.page.keyboard.press(undoKeys)
    assert.equal(await h.css('border-radius'), '18px')
    assert.equal((await h.journal())[0].undone, undefined)

    await h.app.evaluate(() => { document.body.tabIndex = -1; document.body.focus() })
    await h.page.keyboard.press(undoKeys); await h.settled()
    assert.equal(await h.css('border-radius'), '0px')
    assert.deepEqual(await h.journal(), [])

    await h.enter('Corner radius', 18); await h.settled()
    await h.enter('Corner radius', 19); await h.settled()
    await h.app.evaluate(() => { window.__settings.holdUndo = true })
    await undo.click()
    await h.app.waitForFunction(() => typeof window.__releaseUndo === 'function')
    await h.app.evaluate(() => {
      window.__settings.holdUndo = false
      window.__releaseUndo()
    })
    await h.settled()
    assert.equal(await undo.evaluate(el => el === el.getRootNode().activeElement), true)
    assert.equal(await h.css('border-radius'), '18px')
    await h.page.keyboard.press(undoKeys); await h.settled()
    assert.equal(await h.css('border-radius'), '0px')
  } finally { await h.close() }
})

test('alignment hover and keyboard focus reveal a glyph without changing selection', async () => {
  const h = await createHarness()
  try {
    await h.open(); await h.select()
    const grid = h.host.getByRole('group', { name: 'Container alignment' })
    const active = grid.getByRole('button', { pressed: true })
    const candidate = grid.getByRole('button', { name: 'Distribute end, align end' })
    const glyph = candidate.locator('svg')
    assert.equal(await glyph.isVisible(), false)
    await candidate.hover()
    assert.equal(await glyph.isVisible(), true)
    assert.equal(await active.count(), 1)
    assert.notEqual(await candidate.evaluate(node => getComputedStyle(node).color),
      await active.evaluate(node => getComputedStyle(node).color))
    assert.equal(await candidate.evaluate(node => getComputedStyle(node).backgroundColor), 'rgba(0, 0, 0, 0)')
    await h.host.locator('#close-inspector').hover()
    assert.equal(await glyph.isVisible(), false)

    const previous = grid.getByRole('button', { name: 'Distribute center, align end' })
    await previous.focus()
    await h.page.keyboard.press('Tab')
    assert.equal(await candidate.evaluate(node => node.matches(':focus-visible')), true)
    assert.equal(await glyph.isVisible(), true)
    assert.equal((await h.journal()).length, 0)
  } finally { await h.close() }
})

test('horizontal baseline settings keep focus and restore the prior cross-axis alignment', async () => {
  const h = await createHarness({ failSave: 2 })
  try {
    await h.app.locator('body > #target').evaluate(node => { node.style.alignItems = 'stretch' })
    await h.open(); await h.select()
    await h.host.getByRole('button', { name: 'Auto layout settings', exact: true }).click()
    const dialog = h.host.getByRole('dialog', { name: 'Auto layout settings' })
    const baseline = dialog.getByRole('group', { name: 'Align text baseline' })
    const on = baseline.getByRole('button', { name: 'On' })
    const off = baseline.getByRole('button', { name: 'Off' })
    const cross = dialog.getByRole('button', { name: 'CSS cross-axis alignment' })
    assert.equal(await cross.innerText(), 'Stretch')
    await on.press('Enter')
    await h.settled()
    assert.equal(await h.css('align-items'), 'baseline')
    assert.equal(await on.getAttribute('aria-pressed'), 'true')
    assert.equal(await cross.innerText(), 'Baseline')
    assert.equal(await on.evaluate(node => node === node.getRootNode().activeElement), true)
    const settings = h.host.getByRole('button', { name: 'Auto layout settings', exact: true })
    assert.equal(await settings.getAttribute('aria-expanded'), 'true')
    await off.click()
    await h.settled()
    assert.equal(await h.css('align-items'), 'baseline')
    assert.equal(await on.getAttribute('aria-pressed'), 'true')
    assert.equal(await cross.innerText(), 'Baseline')
    assert.equal(await off.evaluate(node => node === node.getRootNode().activeElement), true)
    await off.press('Enter')
    await h.settled()
    assert.equal(await h.css('align-items'), 'stretch')
    assert.equal(await off.getAttribute('aria-pressed'), 'true')
    await cross.click()
    const start = dialog.getByRole('menuitemradio', { name: 'Start', exact: true })
    const stretch = dialog.getByRole('menuitemradio', { name: 'Stretch', exact: true })
    const preview = dialog.locator('.li-settings-preview-frame')
    await start.hover()
    assert.equal(await preview.evaluate(node => node.style.alignItems), 'start')
    assert.equal(await h.css('align-items'), 'stretch')
    assert.equal(await stretch.getAttribute('aria-checked'), 'true')
    assert.equal(await stretch.evaluate(node => getComputedStyle(node).backgroundColor), 'rgba(0, 0, 0, 0)')
    await dialog.getByText('Auto layout settings', { exact: true }).hover()
    assert.equal(await preview.evaluate(node => node.style.alignItems), 'stretch')
    await stretch.press('ArrowUp')
    assert.notEqual(await preview.evaluate(node => node.style.alignItems), 'stretch')
    await h.page.keyboard.press('Escape')
    assert.equal(await preview.evaluate(node => node.style.alignItems), 'stretch')
    await cross.click()
    await start.click()
    await h.settled()
    assert.equal(await cross.innerText(), 'Start')
    assert.equal(await settings.getAttribute('aria-expanded'), 'true')
    assert.equal(await h.css('align-items'), 'start')
    assert.deepEqual((await h.journal()).map(edit => edit.requested), ['baseline', 'stretch', 'start'])
  } finally { await h.close() }
})
